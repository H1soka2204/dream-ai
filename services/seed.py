def _ensure_user(name, email, role, password):
    user = User.query.filter_by(email=email).first()
    if user:
        return user
    user = User(name=name, email=email, role=role)
    user.set_password(password)
    db.session.add(user)
    return user


def _ensure_course(data, teacher_id):
    course = Course.query.filter_by(title=data["title"]).first()
    if not course:
        course = Course(
            title=data["title"],
            description=data["description"],
            topic=data["topic"],
            difficulty=data["difficulty"],
            accent=data["accent"],
            teacher_id=teacher_id,
            status="published",
        )
        db.session.add(course)
        db.session.flush()
        return course

    course.description = data["description"]
    course.topic = data["topic"]
    course.difficulty = data["difficulty"]
    course.accent = data["accent"]
    course.teacher_id = course.teacher_id or teacher_id
    course.status = "published"
    return course


def _ensure_lessons(course, lessons):
    existing = {lesson.title: lesson for lesson in course.lessons}
    for index, lesson_data in enumerate(lessons, start=1):
        title, content = lesson_data
        lesson = existing.get(title)
        if not lesson:
            lesson = Lesson(course_id=course.id, title=title)
            db.session.add(lesson)
        lesson.content = content
        lesson.position = index
        lesson.estimated_minutes = 10 + index * 2


def _ensure_test(course, teacher_id, data):
    title = f"{data['title']}: итоговый тест"
    test = Test.query.filter_by(course_id=course.id, title=title).first()
    if not test:
        test = Test(
            course_id=course.id,
            teacher_id=teacher_id,
            title=title,
            description=f"Проверка знаний по предмету «{data['title']}» и его ключевым темам.",
            difficulty=data["difficulty"],
            time_limit_minutes=20,
            passing_score=70,
        )
        db.session.add(test)
        db.session.flush()
        return test

    test.teacher_id = test.teacher_id or teacher_id
    test.description = f"Проверка знаний по предмету «{data['title']}» и его ключевым темам."
    test.difficulty = data["difficulty"]
    test.time_limit_minutes = 20
    test.passing_score = 70
    return test


def _ensure_questions(test, questions):
    existing = {question.text: question for question in test.questions}
    for question_data in questions:
        question = existing.get(question_data["text"])
        if not question:
            question = Question(
                test_id=test.id,
                text=question_data["text"],
                topic=question_data["topic"],
                difficulty=test.difficulty,
                explanation=question_data["explanation"],
            )
            db.session.add(question)
            db.session.flush()
            _add_answers(question, question_data["answers"], question_data["correct_index"])
            continue

        question.topic = question_data["topic"]
        question.explanation = question_data["explanation"]
        question.difficulty = test.difficulty
        if len(question.answers) < 4:
            _add_answers(question, question_data["answers"], question_data["correct_index"])


def _add_answers(question, answers, correct_index):
    for index, answer_text in enumerate(answers):
        db.session.add(
            Answer(
                question_id=question.id,
                text=answer_text,
                is_correct=index == correct_index,
            )
        )


